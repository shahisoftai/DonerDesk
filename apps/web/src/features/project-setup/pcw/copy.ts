import type { RequirementCode, SlideKey } from "@donordesk/domain";

/**
 * The Project Creation Wizard's wording (Phase 38). English first: the other three languages are added in batch 38.10 against
 * this same shape. Every requirement sentence is keyed on the domain's `RequirementCode`, so a code without a sentence does
 * not compile. Sentences name what is wrong and what to do, never a code or an id.
 */
export type Params = Readonly<Record<string, string | number>>;
const more = (p: Params): string => (Number(p.count ?? 1) > 1 ? ` and ${Number(p.count) - 1} more` : "");
const first = (p: Params): string => String(p.first ?? "");

