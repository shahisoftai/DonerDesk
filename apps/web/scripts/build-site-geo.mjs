#!/usr/bin/env node
// Regenerates the bundled geo data for the site map (Phase 30, memorybank/imp/phase30-maps.md §1).
//
// Sources (Natural Earth, public domain) — download once from
// https://github.com/nvkelso/natural-earth-vector/tree/master/geojson :
//   ne_110m_admin_0_countries.geojson        (country outlines)
//   ne_10m_admin_1_states_provinces.geojson  (province outlines)
//   ne_10m_populated_places_simple.geojson   (place gazetteer)
//
// Usage: node apps/web/scripts/build-site-geo.mjs <world.geojson> <admin1.geojson> <places.geojson>
// Writes world-geo.ts, admin1-geo.ts and gazetteer.ts next to site-map.ts. Run from the repo root.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT_DIR = join(dirname(fileURLToPath(import.meta.url)), "../src/features/workplan/domain/geo");
const EPSILON = 0.05; // ~5 km simplification for province outlines

function distToSegment(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  if (dx === 0 && dy === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy)));
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}

function douglasPeucker(points, epsilon) {
  if (points.length <= 3) return points;
  let maxDistance = 0;
  let index = 0;
  const first = points[0];
  const last = points[points.length - 1];
  for (let i = 1; i < points.length - 1; i++) {
    const d = distToSegment(points[i], first, last);
    if (d > maxDistance) {
      maxDistance = d;
      index = i;
    }
  }
  if (maxDistance <= epsilon) return [first, last];
  const left = douglasPeucker(points.slice(0, index + 1), epsilon);
  const right = douglasPeucker(points.slice(index), epsilon);
  return left.slice(0, -1).concat(right);
}

const round2 = (value) => Math.round(value * 100) / 100;
const roundCoords = (c) => (typeof c[0] === "number" ? [round2(c[0]), round2(c[1])] : c.map(roundCoords));
const simplifyRing = (ring) => (ring.length <= 4 ? ring : douglasPeucker(ring, EPSILON));

function simplifyGeometry(geometry) {
  if (geometry.type === "Polygon") {
    const rings = geometry.coordinates.map(simplifyRing).filter((r) => r.length >= 4);
    return rings.length ? { type: "Polygon", coordinates: rings } : null;
  }
  const polygons = geometry.coordinates
    .map((poly) => poly.map(simplifyRing).filter((r) => r.length >= 4))
    .filter((poly) => poly.length);
  return polygons.length ? { type: "MultiPolygon", coordinates: polygons } : null;
}

const normalize = (s) => s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().trim();
const [worldSrc, admin1Src, placesSrc] = process.argv.slice(2);

// --- countries ---
const world = JSON.parse(readFileSync(worldSrc, "utf8"));
const worldFeatures = [];
for (const f of world.features) {
  const geometry = simplifyGeometry(f.geometry);
  if (!geometry) continue;
  worldFeatures.push({
    type: "Feature",
    properties: { name: f.properties.NAME || f.properties.ADMIN, iso: f.properties.ISO_A2_EH === "-99" ? undefined : f.properties.ISO_A2_EH },
    geometry,
  });
}

// --- provinces ---
const admin1 = JSON.parse(readFileSync(admin1Src, "utf8"));
const admin1Features = [];
for (const f of admin1.features) {
  const geometry = simplifyGeometry(f.geometry);
  const iso = f.properties.iso_a2;
  if (!geometry || !f.properties.name || !iso || iso === "-99") continue;
  admin1Features.push({
    type: "Feature",
    properties: { name: f.properties.name, iso, country: f.properties.admin ?? undefined },
    geometry,
  });
}

// --- gazetteer ---
const places = JSON.parse(readFileSync(placesSrc, "utf8"));
const byKey = new Map();
for (const f of places.features) {
  const p = f.properties;
  const name = p.nameascii || p.name;
  if (!name) continue;
  const row = {
    name,
    alt: p.name && p.nameascii && normalize(p.name) !== normalize(p.nameascii) ? p.name : undefined,
    c: p.adm0name || p.sov0name,
    p1: p.adm1name || undefined,
    lat: round2(p.latitude),
    lng: round2(p.longitude),
    pop: p.pop_max && p.pop_max > 0 ? p.pop_max : 0,
  };
  const key = `${normalize(name)}|${normalize(row.c)}|${normalize(row.p1 ?? "")}`;
  const previous = byKey.get(key);
  if (!previous || row.pop > previous.pop) byKey.set(key, row);
}
const gazetteer = [...byKey.values()].sort((a, b) => b.pop - a.pop);

const emit = (header, declaration, value) => `${header}\n${declaration} ${JSON.stringify(value)};\n`;

writeFileSync(
  join(OUT_DIR, "geo-types.ts"),
  `// Bundled geo shapes for the site map (generated by apps/web/scripts/build-site-geo.mjs). Pure data.
export interface NamedGeoFeature {
  type: "Feature";
  properties: { name: string; iso?: string; country?: string };
  /** GeoJSON geometry, opaque to the app: only ECharts reads the coordinates. */
  geometry: unknown;
}
export interface NamedGeoCollection {
  type: "FeatureCollection";
  features: readonly NamedGeoFeature[];
}
`,
);

writeFileSync(
  join(OUT_DIR, "world-geo.ts"),
  emit(
    '// Country outlines, Natural Earth 110m, simplified. Generated by apps/web/scripts/build-site-geo.mjs — do not edit.',
    'import type { NamedGeoCollection } from "./geo-types";\n\nexport const WORLD_GEO: NamedGeoCollection =',
    { type: "FeatureCollection", features: worldFeatures.map((f) => ({ ...f, geometry: { type: f.geometry.type, coordinates: roundCoords(f.geometry.coordinates) } })) },
  ),
);

writeFileSync(
  join(OUT_DIR, "admin1-geo.ts"),
  emit(
    '// Province/state outlines, Natural Earth 10m simplified to ~5 km. Generated by apps/web/scripts/build-site-geo.mjs — do not edit.',
    'import type { NamedGeoCollection } from "./geo-types";\n\nexport const ADMIN1_GEO: NamedGeoCollection =',
    { type: "FeatureCollection", features: admin1Features.map((f) => ({ ...f, geometry: { type: f.geometry.type, coordinates: roundCoords(f.geometry.coordinates) } })) },
  ),
);

writeFileSync(
  join(OUT_DIR, "gazetteer.ts"),
  `// Populated places, Natural Earth 10m. Generated by apps/web/scripts/build-site-geo.mjs — do not edit.
export interface GazetteerPlace {
  name: string;
  /** Spelled-with-diacritics variant, when it differs from \`name\`. */
  alt?: string;
  /** Country name. */
  c: string;
  /** Province/state name, when known. */
  p1?: string;
  lat: number;
  lng: number;
  pop: number;
}

export const GAZETTEER: readonly GazetteerPlace[] = ${JSON.stringify(gazetteer)};
`,
);

console.log(`world: ${worldFeatures.length} countries, admin1: ${admin1Features.length} provinces, gazetteer: ${gazetteer.length} places -> ${OUT_DIR}`);
