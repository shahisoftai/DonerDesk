import { chromium } from "@playwright/test";
const out = process.argv[2];
const b = await chromium.connectOverCDP("http://127.0.0.1:9340");
const p = b.contexts()[0].pages()[0];
await p.goto("https://donordesk.online/dashboard", { waitUntil: "networkidle" });
await p.keyboard.press("Control+k");
await p.waitForSelector('[aria-label="Search and commands"]');
await p.keyboard.type("demo", { delay: 60 });
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/t-palette.png` });
const rows = await p.$$eval('#cmd-list [role="option"]', (els) => els.slice(0, 6).map((e) => e.textContent?.trim()));
console.log(rows.join(" | "));
await p.keyboard.press("Escape");
await p.keyboard.press("?");
await p.waitForTimeout(400);
console.log("shortcuts:", await p.locator('[aria-label="Keyboard shortcuts"]').count());
await p.keyboard.press("Escape");
await b.close();
