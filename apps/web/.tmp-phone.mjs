import { chromium } from "@playwright/test";
const out = process.argv[2];
const b = await chromium.connectOverCDP("http://127.0.0.1:9340");
const ctx = b.contexts()[0];
const p = await ctx.newPage();
await p.setViewportSize({ width: 390, height: 844 });
await p.goto("https://donordesk.online/projects/cd291c72-ebc9-4f16-8633-b7c9007507ed", { waitUntil: "networkidle" });
await p.screenshot({ path: `${out}/t-phone.png` });
const wide = await p.evaluate(() => { const out=[]; for (const el of document.querySelectorAll("body *")) { const r=el.getBoundingClientRect(); if (r.right>400 && r.width>0) out.push(el.tagName+"."+String(el.className).slice(0,80)+" w="+Math.round(r.width)+" r="+Math.round(r.right)); } return out.slice(0,12).join("\n"); });
console.log("scrollWidth", wide);
await p.close();
await b.close();
