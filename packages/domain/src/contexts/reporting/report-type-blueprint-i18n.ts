/**
 * Display titles for the built-in report-type blueprints in the report
 * languages DonorDesk offers (reporting profile: en, fr, ar, ur, ps).
 *
 * Only what the reader sees is translated: section titles and the headers of
 * the deterministic participants table. The English title stays on the section
 * as its `canonicalTitle`, because section roles (executive summary drafted
 * last, challenge/lesson outlines, annex tables) are recognised from English
 * titles by the writer and the AI worker.
 *
 * French is a reviewed translation; Arabic, Urdu and Pashto are first drafts
 * that need a native speaker's review before they are relied on.
 */

export const BLUEPRINT_LANGUAGES = ["en", "fr", "ar", "ur", "ps"] as const;
export type BlueprintLanguage = (typeof BLUEPRINT_LANGUAGES)[number];

/** Accepts a profile language ("fr", "FR", "fr-FR", "French"); unknown → "en". */
export function normalizeReportLanguage(language: string | undefined): BlueprintLanguage {
  const l = (language ?? "").trim().toLowerCase();
  const byName: Record<string, BlueprintLanguage> = { english: "en", french: "fr", francais: "fr", "français": "fr", arabic: "ar", urdu: "ur", pashto: "ps", pushto: "ps" };
  if (byName[l]) return byName[l]!;
  const code = l.slice(0, 2);
  return (BLUEPRINT_LANGUAGES as readonly string[]).includes(code) ? (code as BlueprintLanguage) : "en";
}

