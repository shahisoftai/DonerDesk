export const BLUEPRINT_CATALOGS: Readonly<Record<Exclude<BlueprintLanguage, "en">, Catalog>> = { fr: FR, ar: AR, ur: UR, ps: PS };

/** The display form of an English blueprint string; the English itself when untranslated. */
export function translateBlueprintText(english: string, language: string | undefined): string {
  const lang = normalizeReportLanguage(language);
  if (lang === "en") return english;
  return BLUEPRINT_CATALOGS[lang][english] ?? english;
}
