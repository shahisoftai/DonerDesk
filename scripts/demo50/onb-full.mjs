import { attach, BASE } from "../demo-ui/lib.mjs";
const { page, browser } = await attach("onb-full");
const S = process.env.S; const log = (...a) => console.log(...a);
page.on("pageerror", (e) => log("PAGEERROR", String(e).slice(0, 200)));
const where = () => new URL(page.url()).pathname;
await page.context().clearCookies();
await page.goto(BASE + "/signup", { waitUntil: "domcontentloaded" });
await page.locator("#name").fill("ZZ Test Onboarding 2");
await page.locator("#email").fill(process.env.EMAIL);
await page.locator("#password").fill(process.env.PW);
await page.locator("#orgName").fill("ZZ TEST Onboarding Demo 2");
await page.locator("#country").fill("Kenya");
await page.locator("form button[type=submit]").click();
await page.waitForURL((u) => !/signup/.test(u.pathname), { timeout: 60000 });
await page.waitForTimeout(4000);
log("after signup:", where(), "|", await page.locator("h1").first().textContent());
// storage button now returns to setup
await page.goto(BASE + "/onboarding/storage", { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Use DonorDesk storage" }).click();
await page.waitForURL((u) => !/storage/.test(u.pathname), { timeout: 15000 });
log("storage button ->", where());
await page.goto(BASE + "/onboarding/reporting-defaults", { waitUntil: "networkidle" });
await page.locator("#tone").selectOption({ index: 1 });
await page.getByRole("button", { name: "Save defaults" }).click();
await page.waitForTimeout(3000);
await page.goto(BASE + "/onboarding", { waitUntil: "networkidle" });
await page.locator("#legal-consent input[type=checkbox]").check();
await page.getByRole("button", { name: /Accept and finish setup/ }).click();
await page.getByText("Terms accepted").waitFor({ timeout: 20000 });
await page.getByText("Setup complete").waitFor({ timeout: 10000 }).then(() => log("Setup complete banner shown without refresh")).catch(() => log("NO banner without refresh"));
log((await page.locator("ol > li").first().innerText()).replace(/\s+/g, " ").slice(0, 100));
await page.screenshot({ path: S + "/07-complete.png", fullPage: true });
await page.getByRole("link", { name: "Create your first project" }).click().catch(() => {});
await page.waitForTimeout(3000); log("first project link ->", where());
await browser.close(); process.exit(0);
