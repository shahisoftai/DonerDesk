import { attach } from "../demo-ui/lib.mjs";
const { page, browser } = await attach("linkfilter");
const bad = [];
page.on("response", (r) => { if (r.status() >= 400) bad.push(`${r.status()} ${r.url().slice(0, 120)}`); });
await page.goto("https://donordesk.online/shared/canvas/8vSHMDmxiJNJG7S4YElUSj3q9Wac2fsC", { waitUntil: "domcontentloaded" });
await page.locator("[data-filter=Province]").waitFor({ timeout: 40000 });
await page.waitForTimeout(6000);
const read = () => page.evaluate(() => ({ url: location.search, cards: [...document.querySelectorAll('[data-testid="multi-card"]')].map((c) => c.innerText.replace(/\s+/g, " ").slice(0, 90)), map: [...document.querySelectorAll("section[data-card]")].map((e) => e.getAttribute("data-card")).join(",") }));
console.log("before:", JSON.stringify(await read()));
const prov = page.locator("[data-filter=Province]"); await prov.locator("summary").click();
await prov.getByLabel("Karnali", { exact: true }).check();
await page.waitForTimeout(9000);
console.log("Karnali:", JSON.stringify(await read()));
const dist = page.locator("[data-filter=District]"); await dist.locator("summary").click();
console.log("districts offered:", (await dist.locator("label").allInnerTexts()).join(", "));
console.log("province options:", (await prov.locator("label").allInnerTexts()).join(", "));
const month = page.locator("[data-filter=Month]"); await month.locator("summary").click();
console.log("months:", (await month.locator("label").allInnerTexts()).join(", "));
const html = await page.content();
console.log("names leaked:", ["European Union", "USAID", "UNICEF", "Karnali Nutrition Alliance"].filter((n) => html.includes(n)));
console.log("errors:", bad.join(" | ") || "none");
await browser.close(); process.exit(0);
