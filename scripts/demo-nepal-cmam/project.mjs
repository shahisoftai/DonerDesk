import { attach, BASE } from "../demo-ui/lib.mjs"; import { writeFileSync } from "node:fs";
import { PROJECT as X } from "./data.mjs";
const { page, browser } = await attach("project");
await page.goto(BASE + "/projects/new"); await page.waitForLoadState("networkidle");
await page.fill("#title", X.title);
await page.fill("#projectCode", X.code + "-" + Date.now().toString(36).toUpperCase());
await page.fill("#donorName", X.donor);
await page.fill("#implementingOrganization", "Terai Community Nutrition Initiative (TCNI)");
await page.fill("#partnerOrganization", "Banke District Public Health Office");
await page.getByRole("button", { name: "Next" }).click();
await page.fill("#country", X.country); await page.fill("#region", X.region); await page.fill("#district", X.district);
await page.selectOption("#sector", { label: "Nutrition" });
await page.fill("#startDate", X.start); await page.fill("#endDate", X.end);
await page.getByRole("button", { name: "Next" }).click();
await page.selectOption("#reportingFrequency", { label: "Monthly" });
await page.fill("#budgetAmount", String(X.budget)); await page.fill("#budgetCurrency", X.currency);
await page.fill("#primaryContactName", "Sunita Thapa");
await page.fill("#description", X.description);
await page.getByRole("button", { name: "Create project" }).click();
await page.waitForURL(/\/projects\/[0-9a-f-]{36}/, { timeout: 60000 });
const P = page.url().match(/projects\/([0-9a-f-]{36})/)[1]; writeFileSync("pid.txt", P); console.log("PROJECT", P, page.url());
await page.waitForLoadState("networkidle"); await page.waitForTimeout(2500);
console.log((await page.locator("main").innerText()).replace(/\n+/g, " | ").slice(0, 1800));
await browser.close(); process.exit(0);
