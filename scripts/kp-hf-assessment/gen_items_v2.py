"""Reads out/doc.txt (made by ext.py from the Master Version 2.0 tool) and writes the kit's item data file."""
import re, os, json
HERE = os.path.dirname(os.path.abspath(__file__))
lines = open(os.path.join(HERE, 'out', 'doc.txt')).read().split('\n')
MOD = re.compile(r'^P: MODULE ([A-Z]{1,2}) – (.*)$')
mods = []; cur = None; purpose = None
for i, l in enumerate(lines):
    m = MOD.match(l)
    if m:
        cur = dict(code=m.group(1), title=m.group(2).strip().title().replace('Ipc', 'IPC').replace('(Ipc)', '(IPC)'), purpose='', items=[]); mods.append(cur); continue
    if cur is None: continue
    if l.startswith('P: Purpose:'): cur['purpose'] = l[3:].strip()
    elif l.startswith('P: APPENDIX'): cur = None
    elif l.startswith('R: ') and re.match(r'^R: ' + cur['code'] + r'-\d+ \|', l):
        c = [x.strip() for x in l[3:].split(' | ')] + ['', '', '']
        cur['items'].append(dict(id=c[0], q=c[1], hint=c[2], ev=c[3]))
tot = sum(len(m['items']) for m in mods)
def ts(s): return json.dumps(s, ensure_ascii=False)
out = ['// Generated by scripts/kp-hf-assessment/gen_items_v2.py from the KP Health Foundation Master Version 2.0 tool. Do not edit by hand.',
       'export interface HfaV2Item { id: string; question: string; response: string; evidence: string }',
       'export interface HfaV2Module { code: string; title: string; purpose: string; items: ReadonlyArray<HfaV2Item> }',
       'export const HFA_V2_MODULES: ReadonlyArray<HfaV2Module> = [']
for m in mods:
    out.append(f'  {{ code: {ts(m["code"])}, title: {ts(m["title"])}, purpose: {ts(m["purpose"].replace("Purpose: ", ""))}, items: [')
    for it in m['items']:
        out.append(f'    {{ id: {ts(it["id"])}, question: {ts(it["q"])}, response: {ts(it["hint"])}, evidence: {ts(it["ev"])} }},')
    out.append('  ] },')
out.append('];')
dst = 'packages/domain/src/contexts/collection/kits/health-facility-v2-items.ts'
open(dst, 'w').write('\n'.join(out) + '\n')
print(len(mods), 'modules', tot, 'items', [m['code'] for m in mods])
